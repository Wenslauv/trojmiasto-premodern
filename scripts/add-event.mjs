import { readFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { validateEvent, validateEventsArray } from './lib/events-validation.mjs';
import { normalizeIncomingEvent } from './lib/normalize-incoming-event.mjs';
import { loadPlayers, savePlayers } from './lib/players.mjs';
import { EVENTS_DIR, assertNotImportedTwice, eventFileName, loadEventFiles, sortEvents, writeEventFile } from './lib/event-store.mjs';

const root = process.cwd();

function parseArg(flag) {
  const idx = process.argv.indexOf(flag);
  if (idx === -1) return null;
  return process.argv[idx + 1] ?? null;
}

function parseBoolean(flag) {
  return process.argv.includes(flag);
}

function slugify(value) {
  return String(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

function generateEventId(incomingEvent, currentEvents) {
  if (typeof incomingEvent.id === 'string' && incomingEvent.id.trim() !== '') {
    return incomingEvent.id.trim();
  }

  const baseDate = String(incomingEvent.date ?? '').replace(/-/g, '');
  const baseName = slugify(incomingEvent.name ?? 'event');
  const base = `${baseDate || 'event'}-${baseName || 'event'}`;
  const existing = new Set(currentEvents.map((event) => event.id));

  if (!existing.has(base)) return base;

  let n = 2;
  while (existing.has(`${base}-${n}`)) {
    n += 1;
  }
  return `${base}-${n}`;
}

function logNewPlayers(newPlayers, title) {
  if (newPlayers.length === 0) return;
  console.log(`${title}: ${newPlayers.map((player) => `${player.id} (${player.name})`).join(', ')}`);
}

async function main() {
  const fileArg = parseArg('--file');
  const dryRun = parseBoolean('--dry-run');
  const deleteSource = parseBoolean('--delete-source');
  const allowSameDay = parseBoolean('--allow-same-day');

  if (!fileArg) {
    throw new Error('Usage: node scripts/add-event.mjs --file <path-to-event.json> [--dry-run] [--delete-source] [--allow-same-day]');
  }

  const incomingPath = path.resolve(root, fileArg);
  const incomingRaw = await readFile(incomingPath, 'utf8');
  const incomingEvent = JSON.parse(incomingRaw);

  const entries = await loadEventFiles(root);
  const currentEvents = entries.map((entry) => entry.event);
  validateEventsArray(currentEvents);

  const players = await loadPlayers(root);
  const { event: normalizedIncomingEvent, newPlayers } = normalizeIncomingEvent(incomingEvent, players);
  normalizedIncomingEvent.id = generateEventId(normalizedIncomingEvent, currentEvents);
  validateEvent(normalizedIncomingEvent, 'incomingEvent');

  const duplicate = currentEvents.find((event) => event.id === normalizedIncomingEvent.id);
  if (duplicate) {
    throw new Error(`Event with id "${normalizedIncomingEvent.id}" already exists in ${EVENTS_DIR}.`);
  }
  assertNotImportedTwice(currentEvents, normalizedIncomingEvent, allowSameDay);

  validateEventsArray(sortEvents([...currentEvents, normalizedIncomingEvent]));
  const file = eventFileName(normalizedIncomingEvent, entries.map((entry) => entry.file));

  if (dryRun) {
    console.log(`Dry run OK. Event ${normalizedIncomingEvent.id} can be added as ${EVENTS_DIR}/${file}.`);
    logNewPlayers(newPlayers, 'Would add new players');
    return;
  }

  const written = await writeEventFile(root, file, normalizedIncomingEvent);
  console.log(`Added event ${normalizedIncomingEvent.id} -> ${written}`);
  if (newPlayers.length > 0) {
    await savePlayers(root, [...players, ...newPlayers]);
    logNewPlayers(newPlayers, 'Added new players to data/players.json');
  }

  if (deleteSource) {
    await unlink(incomingPath);
    console.log(`Deleted source file ${fileArg}`);
  }

  console.log('Next step: commit the event file (and data/players.json when new players were added). Site data is regenerated by npm run generate-data.');
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
